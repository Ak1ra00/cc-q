def parse(src):
    glyphs = {}
    cur = None
    rows = []
    for line in src.strip('\n').split('\n'):
        if line.startswith('[') and line.endswith(']') and len(line) >= 3:
            if cur is not None:
                glyphs[cur] = rows
            name = line[1:-1]
            if name.startswith('\\x'):
                cur = int(name[2:], 16)
            else:
                assert len(name) == 1, name
                cur = ord(name)
            rows = []
        else:
            assert len(line) == 5, (chr(cur) if cur else cur, line)
            rows.append(line)
    glyphs[cur] = rows
    return glyphs

def main(out_path):
    glyphs = parse(GLYPHS)
    data = []
    for code in range(128):
        rows = glyphs.get(code)
        if rows is None:
            rows = []
        assert len(rows) <= 9, (code, rows)
        rows = rows + ['.....'] * (9 - len(rows))
        for r in rows:
            v = 0
            for i, ch in enumerate(r):
                if ch == '#':
                    v |= 1 << (4 - i)
            data.append(v)

    missing = [chr(c) for c in range(32, 127) if c not in glyphs]
    assert not missing, missing

    with open(out_path, 'w') as f:
        f.write('// generated by tools/gen_font.py -- do not edit\n')
        f.write('#include <stdint.h>\n\n')
        f.write('// 128 glyphs x 9 rows, 5 bits per row (MSB = left)\n')
        f.write('const uint8_t g_font5x9[128 * 9] = {\n')
        for code in range(128):
            chunk = data[code * 9:(code + 1) * 9]
            label = chr(code) if 32 < code < 127 and chr(code) not in '\\' else '0x%02x' % code
            f.write('    ' + ', '.join('0x%02x' % v for v in chunk) + ',  // %s\n' % label)
        f.write('};\n')

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else
         os.path.join(os.path.dirname(__file__), '..', 'game', 'font_gen.c'))
